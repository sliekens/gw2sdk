using System.Diagnostics.CodeAnalysis;
using System.Text.Json;
using System.Text.Json.Serialization;
#if NET
using System.Text.Json.Serialization.Metadata;
#endif

namespace GuildWars2.Collections;

/// <summary>JSON converter factory for <see cref="ImmutableValueList{T}"/>.</summary>
public sealed partial class ImmutableValueListJsonConverter : JsonConverterFactory
{
    /// <inheritdoc />
    public override bool CanConvert(Type typeToConvert)
    {
        ThrowHelper.ThrowIfNull(typeToConvert);
        if (!typeToConvert.IsGenericType)
        {
            return false;
        }

        Type genericTypeDefinition = typeToConvert.GetGenericTypeDefinition();
        return genericTypeDefinition == typeof(ImmutableValueList<>);
    }

    /// <inheritdoc />
    public override JsonConverter CreateConverter(
        Type typeToConvert,
        JsonSerializerOptions options
    )
    {
        ThrowHelper.ThrowIfNull(typeToConvert);
        Type elementType = typeToConvert.GetGenericArguments()[0];
        return CreateKnownConverter(elementType) ?? CreateConverterAtRuntime(typeToConvert, elementType);
    }

    /// <summary>Creates the converters that Native AOT must compile ahead of time. Generated by
    /// ImmutableValueCollectionConverterGenerator.</summary>
    /// <param name="elementType">The element type.</param>
    /// <returns>The converter, or <c>null</c> when the element type is not known ahead of time.</returns>
    private static partial JsonConverter? CreateKnownConverter(Type elementType);

    [UnconditionalSuppressMessage(
        "AOT",
        "IL3050",
        Justification = "Only reached for element types that the generated CreateKnownConverter does not create statically"
            + " (the value types used by GW2SDK models, common primitives, and a reference-type template). Reference types"
            + " work under Native AOT through shared canonical code. Other value types need code that Native AOT cannot"
            + " generate at runtime; that case throws a NotSupportedException that explains the limitation."
            + " See https://github.com/sliekens/gw2sdk/issues/521."
    )]
    private static JsonConverter CreateConverterAtRuntime(Type typeToConvert, Type elementType)
    {
        try
        {
            return (JsonConverter)Activator.CreateInstance(typeof(Converter<>).MakeGenericType(elementType))!;
        }
        catch (NotSupportedException exception)
        {
            throw ImmutableValueCollectionConverters.NotPrecompiled(typeToConvert, exception);
        }
    }

    private sealed class Converter<T> : JsonConverter<ImmutableValueList<T>>
    {
#if NET
        private JsonTypeInfo<IImmutableList<T>>? typeInfo;
#endif

        public override void Write(Utf8JsonWriter writer, ImmutableValueList<T> value, JsonSerializerOptions options)
        {
#if NET
            JsonSerializer.Serialize(writer, value, ImmutableValueCollectionJson.GetListTypeInfo(ref typeInfo, options));
#else
            JsonSerializer.Serialize<IImmutableList<T>>(writer, value, options);
#endif
        }

        public override ImmutableValueList<T>? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        {
#if NET
            IImmutableList<T>? list = JsonSerializer.Deserialize(ref reader, ImmutableValueCollectionJson.GetListTypeInfo(ref typeInfo, options));
#else
            IImmutableList<T>? list = JsonSerializer.Deserialize<IImmutableList<T>>(ref reader, options);
#endif
            return list is null ? null : [.. list];
        }
    }
}
