using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace GuildWars2.Generators;

/// <summary>Generates JSON converters for data-transfer-object hierarchies that do not already have one.
/// Each converter writes a <c>$type</c> discriminator and every property of the runtime type, so a value stored
/// as its base type deserializes back to the same derived type. See https://github.com/sliekens/gw2sdk/issues/522.</summary>
[Generator]
public sealed class PolymorphicModelJsonConverterGenerator : IIncrementalGenerator
{
    private const string ConverterMetadataName = "System.Text.Json.Serialization.JsonConverter`1";

    private const string ListMetadataName = "GuildWars2.Collections.IImmutableValueList`1";

    private const string SetMetadataName = "GuildWars2.Collections.IImmutableValueSet`1";

    private const string ExtensibleMetadataName = "GuildWars2.Extensible`1";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, static (production, compilation) => Execute(compilation, production));
    }

    private static void Execute(Compilation compilation, SourceProductionContext production)
    {
        if (compilation.GetTypeByMetadataName(ConverterMetadataName) is not INamedTypeSymbol jsonConverter)
        {
            return;
        }

        INamedTypeSymbol? listType = compilation.GetTypeByMetadataName(ListMetadataName);
        INamedTypeSymbol? setType = compilation.GetTypeByMetadataName(SetMetadataName);
        INamedTypeSymbol? extensible = compilation.GetTypeByMetadataName(ExtensibleMetadataName);
        INamedTypeSymbol? coin = compilation.GetTypeByMetadataName("GuildWars2.Coin");
        INamedTypeSymbol? pointF = compilation.GetTypeByMetadataName("System.Drawing.PointF");
        INamedTypeSymbol? vector3 = compilation.GetTypeByMetadataName("System.Numerics.Vector3");
        INamedTypeSymbol? uri = compilation.GetTypeByMetadataName("System.Uri");
        INamedTypeSymbol? dateTimeOffset = compilation.GetTypeByMetadataName("System.DateTimeOffset");
        INamedTypeSymbol? timeSpan = compilation.GetTypeByMetadataName("System.TimeSpan");
        if (listType is null || setType is null || extensible is null)
        {
            return;
        }

        // A collection expression would drop the comparer.
#pragma warning disable IDE0028
        HashSet<INamedTypeSymbol> sourceConverted = new(SymbolEqualityComparer.Default);
        List<INamedTypeSymbol> models = new();
#pragma warning restore IDE0028
        Collect(compilation.GlobalNamespace, jsonConverter, sourceConverted, models);

#pragma warning disable IDE0028
        HashSet<INamedTypeSymbol> polymorphic = new(SymbolEqualityComparer.Default);
#pragma warning restore IDE0028
        foreach (INamedTypeSymbol model in models)
        {
            INamedTypeSymbol root = Root(model);
            if (IsExcluded(root) || sourceConverted.Contains(root) || !HasDescendants(root, models) || !InDataFamily(root))
            {
                continue;
            }

            if (sourceConverted.Contains(model))
            {
                continue;
            }

            polymorphic.Add(model);
        }

#pragma warning disable IDE0028
        HashSet<INamedTypeSymbol> flat = new(SymbolEqualityComparer.Default);
#pragma warning restore IDE0028
        foreach (INamedTypeSymbol model in polymorphic)
        {
            foreach (IPropertySymbol property in Properties(model))
            {
                ConsiderFlat(property.Type, polymorphic, flat, sourceConverted);
            }
        }

        bool grew = true;
        while (grew)
        {
            grew = false;
            foreach (INamedTypeSymbol model in flat.ToList())
            {
                foreach (IPropertySymbol property in Properties(model))
                {
                    if (ConsiderFlat(property.Type, polymorphic, flat, sourceConverted))
                    {
                        grew = true;
                    }
                }
            }
        }

#pragma warning disable IDE0028
        HashSet<INamedTypeSymbol> generated = new(SymbolEqualityComparer.Default);
#pragma warning restore IDE0028
        generated.UnionWith(polymorphic);
        generated.UnionWith(flat);

        Known known = new(listType, setType, extensible, coin, pointF, vector3, uri, dateTimeOffset, timeSpan, polymorphic, generated);
        StringBuilder output = new();
        output.AppendLine("// <auto-generated/>");
        output.AppendLine("#nullable enable");
        output.AppendLine("#pragma warning disable");
        output.AppendLine("using System.Text.Json;");
        output.AppendLine("using System.Text.Json.Serialization;");
        output.AppendLine("using GuildWars2.Json;");
        output.AppendLine();

        foreach (IGrouping<string, INamedTypeSymbol> group in generated
            .GroupBy(static type => type.ContainingNamespace.ToDisplayString())
            .OrderBy(static group => group.Key, StringComparer.Ordinal))
        {
            output.Append("namespace ").Append(group.Key).AppendLine();
            output.AppendLine("{");
            foreach (INamedTypeSymbol type in group.OrderBy(static type => type.Name, StringComparer.Ordinal))
            {
                EmitConverter(output, type, polymorphic.Contains(type), models, known);
            }

            output.AppendLine("}");
            output.AppendLine();
        }

        EmitRegistry(output, generated);
        production.AddSource("GuildWars2.PolymorphicModelJson.g.cs", SourceText.From(output.ToString(), Encoding.UTF8));
    }

    private static void Collect(
        INamespaceSymbol ns,
        INamedTypeSymbol jsonConverter,
        HashSet<INamedTypeSymbol> sourceConverted,
        List<INamedTypeSymbol> models
    )
    {
        foreach (INamedTypeSymbol type in ns.GetTypeMembers())
        {
            CollectType(type, jsonConverter, sourceConverted, models);
        }

        foreach (INamespaceSymbol child in ns.GetNamespaceMembers())
        {
            Collect(child, jsonConverter, sourceConverted, models);
        }
    }

    private static void CollectType(
        INamedTypeSymbol type,
        INamedTypeSymbol jsonConverter,
        HashSet<INamedTypeSymbol> sourceConverted,
        List<INamedTypeSymbol> models
    )
    {
        if (type.BaseType is INamedTypeSymbol { IsGenericType: true } baseType
            && SymbolEqualityComparer.Default.Equals(baseType.OriginalDefinition, jsonConverter)
            && baseType.TypeArguments[0] is INamedTypeSymbol { IsGenericType: false } converted)
        {
            sourceConverted.Add(converted);
        }

        if (type.DeclaredAccessibility == Accessibility.Public
            && type.TypeKind == TypeKind.Class
            && !type.IsStatic
            && !type.IsGenericType
            && type.ContainingType is null
            && IsGuildWars(type))
        {
            models.Add(type);
        }

        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
        {
            CollectType(nested, jsonConverter, sourceConverted, models);
        }
    }

    private static bool ConsiderFlat(
        ITypeSymbol type,
        HashSet<INamedTypeSymbol> polymorphic,
        HashSet<INamedTypeSymbol> flat,
        HashSet<INamedTypeSymbol> sourceConverted
    )
    {
        ITypeSymbol current = Unwrap(type, out _);
        if (current is INamedTypeSymbol { IsGenericType: true } generic && generic.TypeArguments.Length == 1)
        {
            string name = generic.OriginalDefinition.ToDisplayString();
            if (name is "GuildWars2.Collections.IImmutableValueList<T>"
                or "GuildWars2.Collections.IImmutableValueSet<T>"
                or "GuildWars2.Collections.ImmutableValueList<T>"
                or "GuildWars2.Collections.ImmutableValueSet<T>"
                or "GuildWars2.Collections.ImmutableValueArray<T>")
            {
                return ConsiderFlat(generic.TypeArguments[0], polymorphic, flat, sourceConverted);
            }
        }

        if (current is not INamedTypeSymbol candidate || candidate.TypeKind != TypeKind.Class || candidate.SpecialType == SpecialType.System_Object)
        {
            return false;
        }

        if (!IsGuildWars(candidate) || polymorphic.Contains(candidate) || flat.Contains(candidate) || sourceConverted.Contains(candidate))
        {
            return false;
        }

        flat.Add(candidate);
        return true;
    }

    private static void EmitConverter(
        StringBuilder output,
        INamedTypeSymbol type,
        bool polymorphic,
        List<INamedTypeSymbol> models,
        Known known
    )
    {
        string typeName = Fq(type);
        string discriminator = Snake(type.Name);
        List<INamedTypeSymbol> descendants = polymorphic
            ? [.. models.Where(candidate => Inherits(candidate, type) && !SymbolEqualityComparer.Default.Equals(candidate, type))
                .OrderByDescending(Depth)
                .ThenBy(static candidate => candidate.ToDisplayString(), StringComparer.Ordinal)]
            : [];

        output.AppendLine("    internal sealed class " + type.Name + "JsonConverter : JsonConverter<" + typeName + ">");
        output.AppendLine("    {");
        if (polymorphic)
        {
            output.Append("        public const string DiscriminatorValue = \"").Append(discriminator).AppendLine("\";");
            output.AppendLine();
        }

        output.Append("        public override ").Append(typeName).AppendLine(" Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
        output.AppendLine("        {");
        output.AppendLine("            using JsonDocument json = JsonDocument.ParseValue(ref reader);");
        output.AppendLine("            return Read(json.RootElement);");
        output.AppendLine("        }");
        output.AppendLine();
        output.Append("        public override void Write(Utf8JsonWriter writer, ").Append(typeName).AppendLine(" value, JsonSerializerOptions options)");
        output.AppendLine("        {");
        output.AppendLine("            Write(writer, value);");
        output.AppendLine("        }");
        output.AppendLine();
        output.Append("        public static ").Append(typeName).AppendLine(" Read(in JsonElement json)");
        output.AppendLine("        {");
        if (descendants.Count > 0)
        {
            output.AppendLine("            if (json.TryGetProperty(PolymorphicModelJson.DiscriminatorName, out JsonElement discriminator))");
            output.AppendLine("            {");
            output.AppendLine("                switch (discriminator.GetString())");
            output.AppendLine("                {");
            foreach (INamedTypeSymbol descendant in descendants)
            {
                output.Append("                    case ").Append(Converter(descendant)).AppendLine(".DiscriminatorValue:");
                output.Append("                        return ").Append(Converter(descendant)).AppendLine(".Read(json);");
            }

            if (!type.IsAbstract)
            {
                output.AppendLine("                    case DiscriminatorValue:");
                output.AppendLine("                        break;");
            }

            output.AppendLine("                    default:");
            output.AppendLine("                        ThrowHelper.ThrowInvalidDiscriminator(discriminator.GetString());");
            output.AppendLine("                        break;");
            output.AppendLine("                }");
            output.AppendLine("            }");
            if (type.IsAbstract)
            {
                output.AppendLine("            ThrowHelper.ThrowInvalidDiscriminator(json.TryGetProperty(PolymorphicModelJson.DiscriminatorName, out JsonElement missing) ? missing.GetString() : null);");
            }
        }
        else if (polymorphic)
        {
            output.AppendLine("            if (!json.GetProperty(PolymorphicModelJson.DiscriminatorName).ValueEquals(DiscriminatorValue))");
            output.AppendLine("            {");
            output.AppendLine("                ThrowHelper.ThrowInvalidDiscriminator(json.GetProperty(PolymorphicModelJson.DiscriminatorName).GetString());");
            output.AppendLine("            }");
            output.AppendLine();
        }

        if (!type.IsAbstract)
        {
            List<(IPropertySymbol Property, Shape Shape)> properties = Bind(type, known);
            foreach ((IPropertySymbol property, Shape _) in properties)
            {
                output.Append("            JsonElement ").Append(Local(property)).Append(" = json.GetProperty(\"").Append(Snake(property.Name)).AppendLine("\");");
            }

            output.Append("            return new ").Append(typeName).AppendLine();
            output.AppendLine("            {");
            foreach ((IPropertySymbol property, Shape shape) in properties)
            {
                output.Append("                ").Append(property.Name).Append(" = ").Append(ReadExpr(shape, Local(property))).AppendLine(",");
            }

            output.AppendLine("            };");
        }

        output.AppendLine("        }");
        output.AppendLine();
        output.Append("        public static void Write(Utf8JsonWriter writer, ").Append(typeName).AppendLine(" value)");
        output.AppendLine("        {");
        if (descendants.Count > 0)
        {
            bool first = true;
            int derivedIndex = 0;
            foreach (INamedTypeSymbol descendant in descendants)
            {
                string derived = "derived" + derivedIndex;
                derivedIndex++;
                output.Append(first ? "            if" : "            else if");
                output.Append(" (value is ").Append(Fq(descendant)).Append(' ').Append(derived).AppendLine(")");
                output.AppendLine("            {");
                output.Append("                ").Append(Converter(descendant)).Append(".Write(writer, ").Append(derived).AppendLine(");");
                output.AppendLine("            }");
                first = false;
            }

            output.Append(first ? "            if" : "            else if");
            output.Append(" (value.GetType() == typeof(").Append(typeName).AppendLine("))");
            output.AppendLine("            {");
            if (type.IsAbstract)
            {
                output.AppendLine("                ThrowHelper.ThrowInvalidOperationException(\"No JSON converter is registered for \" + value.GetType() + \".\");");
            }
            else
            {
                EmitObject(output, type, known, "                ");
            }

            output.AppendLine("            }");
            output.AppendLine("            else");
            output.AppendLine("            {");
            output.AppendLine("                ThrowHelper.ThrowInvalidOperationException(\"No JSON converter is registered for \" + value.GetType() + \".\");");
            output.AppendLine("            }");
        }
        else if (!type.IsAbstract)
        {
            EmitObject(output, type, known, "            ");
        }
        else
        {
            output.AppendLine("            ThrowHelper.ThrowInvalidOperationException(\"No JSON converter is registered for \" + value.GetType() + \".\");");
        }

        output.AppendLine("        }");
        output.AppendLine("    }");
        output.AppendLine();
    }

    private static void EmitObject(StringBuilder output, INamedTypeSymbol type, Known known, string indent)
    {
        output.Append(indent).AppendLine("writer.WriteStartObject();");
        if (known.Polymorphic.Contains(type))
        {
            output.Append(indent).AppendLine("writer.WriteString(PolymorphicModelJson.DiscriminatorName, DiscriminatorValue);");
        }

        foreach ((IPropertySymbol property, Shape shape) in Bind(type, known))
        {
            EmitWriteProperty(output, property, shape, indent);
        }

        output.Append(indent).AppendLine("writer.WriteEndObject();");
    }

    private static void EmitWriteProperty(StringBuilder output, IPropertySymbol property, Shape shape, string indent)
    {
        string jsonName = Snake(property.Name);
        string access = "value." + property.Name;
        if (!shape.Nullable)
        {
            EmitWriteNonNull(output, shape, jsonName, access, indent, propertyName: true);
            return;
        }

        string present = "present" + property.Name;
        output.Append(indent).Append("if (").Append(access).Append(" is { } ").Append(present).AppendLine(")");
        output.Append(indent).AppendLine("{");
        EmitWriteNonNull(output, shape, jsonName, present, indent + "    ", propertyName: true);
        output.Append(indent).AppendLine("}");
        output.Append(indent).AppendLine("else");
        output.Append(indent).AppendLine("{");
        output.Append(indent).Append("    writer.WriteNull(\"").Append(jsonName).AppendLine("\");");
        output.Append(indent).AppendLine("}");
    }

    private static void EmitWriteNonNull(StringBuilder output, Shape shape, string jsonName, string expr, string indent, bool propertyName)
    {
        switch (shape.Kind)
        {
            case Kind.String:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteString", expr);
                return;
            case Kind.Bool:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteBoolean", expr);
                return;
            case Kind.Int32:
            case Kind.Int64:
            case Kind.Double:
            case Kind.Single:
            case Kind.Decimal:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteNumber", expr);
                return;
            case Kind.DateTime:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteString", expr);
                return;
            case Kind.Time:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteNumber", expr + ".Ticks");
                return;
            case Kind.Uri:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteString", expr + ".OriginalString");
                return;
            case Kind.Coin:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteNumber", expr + ".Amount");
                return;
            case Kind.Enum:
            case Kind.Extensible:
                WriteNamed(output, indent, propertyName, jsonName, "writer.WriteString", expr + ".ToString()");
                return;
            case Kind.PointF:
                Start(output, indent, propertyName, jsonName, array: true);
                output.Append(indent).Append("writer.WriteNumberValue(").Append(expr).AppendLine(".X);");
                output.Append(indent).Append("writer.WriteNumberValue(").Append(expr).AppendLine(".Y);");
                output.Append(indent).AppendLine("writer.WriteEndArray();");
                return;
            case Kind.Vector3:
                Start(output, indent, propertyName, jsonName, array: true);
                output.Append(indent).Append("writer.WriteNumberValue(").Append(expr).AppendLine(".X);");
                output.Append(indent).Append("writer.WriteNumberValue(").Append(expr).AppendLine(".Y);");
                output.Append(indent).Append("writer.WriteNumberValue(").Append(expr).AppendLine(".Z);");
                output.Append(indent).AppendLine("writer.WriteEndArray();");
                return;
            case Kind.Model:
                if (propertyName)
                {
                    output.Append(indent).Append("writer.WritePropertyName(\"").Append(jsonName).AppendLine("\");");
                }

                output.Append(indent).Append(shape.ConverterName).Append(".Write(writer, ").Append(expr).AppendLine(");");
                return;
            case Kind.List:
                Start(output, indent, propertyName, jsonName, array: true);
                output.Append(indent).Append("foreach (").Append(ElementType(shape.Element!)).Append(" item in ").Append(expr).AppendLine(")");
                output.Append(indent).AppendLine("{");
                if (shape.Element!.Nullable)
                {
                    output.Append(indent).AppendLine("    if (item is { } present)");
                    output.Append(indent).AppendLine("    {");
                    EmitWriteNonNull(output, shape.Element, "", "present", indent + "        ", propertyName: false);
                    output.Append(indent).AppendLine("    }");
                    output.Append(indent).AppendLine("    else");
                    output.Append(indent).AppendLine("    {");
                    output.Append(indent).AppendLine("        writer.WriteNullValue();");
                    output.Append(indent).AppendLine("    }");
                }
                else
                {
                    EmitWriteNonNull(output, shape.Element, "", "item", indent + "    ", propertyName: false);
                }

                output.Append(indent).AppendLine("}");
                output.Append(indent).AppendLine("writer.WriteEndArray();");
                return;
            default:
                throw new InvalidOperationException("Unsupported shape " + shape.Kind);
        }
    }

    private static void WriteNamed(StringBuilder output, string indent, bool propertyName, string jsonName, string method, string expr)
    {
        if (propertyName)
        {
            output.Append(indent).Append(method).Append("(\"").Append(jsonName).Append("\", ").Append(expr).AppendLine(");");
        }
        else
        {
            string valueMethod = method + "Value";
            output.Append(indent).Append(valueMethod).Append("(").Append(expr).AppendLine(");");
        }
    }

    private static void Start(StringBuilder output, string indent, bool propertyName, string jsonName, bool array)
    {
        if (propertyName)
        {
            output.Append(indent).Append(array ? "writer.WriteStartArray(\"" : "writer.WriteStartObject(\"").Append(jsonName).AppendLine("\");");
        }
        else
        {
            output.Append(indent).AppendLine(array ? "writer.WriteStartArray();" : "writer.WriteStartObject();");
        }
    }

    private static string ReadExpr(Shape shape, string expr)
    {
        string inner = ReadNonNull(shape, expr);
        if (!shape.Nullable)
        {
            return inner;
        }

        if (shape.IsValueType)
        {
            return expr + ".ValueKind == JsonValueKind.Null ? null : (" + shape.TypeName + "?)(" + inner + ")";
        }

        return expr + ".ValueKind == JsonValueKind.Null ? null : " + inner;
    }

    private static string ReadNonNull(Shape shape, string expr)
    {
        switch (shape.Kind)
        {
            case Kind.String:
                return expr + ".GetStringRequired()";
            case Kind.Bool:
                return expr + ".GetBoolean()";
            case Kind.Int32:
                return expr + ".GetInt32()";
            case Kind.Int64:
                return expr + ".GetInt64()";
            case Kind.Double:
                return expr + ".GetDouble()";
            case Kind.Single:
                return expr + ".GetSingle()";
            case Kind.Decimal:
                return expr + ".GetDecimal()";
            case Kind.DateTime:
                return expr + ".GetDateTimeOffset()";
            case Kind.Time:
                return "global::System.TimeSpan.FromTicks(" + expr + ".GetInt64())";
            case Kind.Uri:
                return "new global::System.Uri(" + expr + ".GetStringRequired(), global::System.UriKind.RelativeOrAbsolute)";
            case Kind.Coin:
                return "new global::GuildWars2.Coin(" + expr + ".GetInt32())";
            case Kind.Enum:
                return "(" + shape.TypeName + ")global::System.Enum.Parse(typeof(" + shape.TypeName + "), " + expr + ".GetStringRequired())";
            case Kind.Extensible:
                return expr + ".GetEnum<" + shape.Argument + ">()";
            case Kind.PointF:
                return "new global::System.Drawing.PointF(" + expr + "[0].GetSingle(), " + expr + "[1].GetSingle())";
            case Kind.Vector3:
                return "new global::System.Numerics.Vector3(" + expr + "[0].GetSingle(), " + expr + "[1].GetSingle(), " + expr + "[2].GetSingle())";
            case Kind.Model:
                return shape.ConverterName + ".Read(" + expr + ")";
            case Kind.List:
                string lambdaBody = ReadNonNull(shape.Element!, "value");
                if (shape.Element!.Nullable)
                {
                    lambdaBody = shape.Element.IsValueType
                        ? "value.ValueKind == JsonValueKind.Null ? null : (" + shape.Element.TypeName + "?)(" + lambdaBody + ")"
                        : "value.ValueKind == JsonValueKind.Null ? null : " + lambdaBody;
                }

                string lambda = "static (in value) => " + lambdaBody;
                string method = shape.IsSet ? "GetSet" : "GetList";
                return expr + "." + method + "(" + lambda + ")";
            default:
                throw new InvalidOperationException("Unsupported shape " + shape.Kind);
        }
    }

    private static string ElementType(Shape element)
    {
        return element.Nullable ? element.TypeName + "?" : element.TypeName;
    }

    private static List<(IPropertySymbol Property, Shape Shape)> Bind(INamedTypeSymbol type, Known known)
    {
        List<(IPropertySymbol, Shape)> properties = [];
        foreach (IPropertySymbol property in Properties(type))
        {
            properties.Add((property, Classify(property.Type, property, known)));
        }

        return properties;
    }

    private static Shape Classify(ITypeSymbol type, IPropertySymbol property, Known known)
    {
        ITypeSymbol current = Unwrap(type, out bool nullable);
        Shape shape = ClassifyCore(current, property, known);
        shape.Nullable = nullable || shape.Nullable;
        return shape;
    }

    private static Shape ClassifyCore(ITypeSymbol type, IPropertySymbol property, Known known)
    {
        if (type is INamedTypeSymbol named)
        {
            if (named.SpecialType == SpecialType.System_String)
            {
                return new Shape(Kind.String, "string", isValueType: false);
            }

            if (SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, known.List) || SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, known.Set))
            {
                Shape element = Classify(named.TypeArguments[0], property, known);
                return new Shape(Kind.List, Fq(named), isValueType: false)
                {
                    Element = element,
                    IsSet = SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, known.Set)
                };
            }

            if (SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, known.Extensible) && named.TypeArguments[0] is INamedTypeSymbol enumType)
            {
                return new Shape(Kind.Extensible, "global::GuildWars2.Extensible<" + Fq(enumType) + ">", isValueType: true)
                {
                    Argument = Fq(enumType)
                };
            }

            if (known.Generated.Contains(named))
            {
                return new Shape(Kind.Model, Fq(named), isValueType: false) { ConverterName = Converter(named) };
            }

            if (named.TypeKind == TypeKind.Enum)
            {
                return new Shape(Kind.Enum, Fq(named), isValueType: true);
            }

            if (known.Coin is not null && SymbolEqualityComparer.Default.Equals(named, known.Coin))
            {
                return new Shape(Kind.Coin, Fq(named), isValueType: true);
            }

            if (known.PointF is not null && SymbolEqualityComparer.Default.Equals(named, known.PointF))
            {
                return new Shape(Kind.PointF, Fq(named), isValueType: true);
            }

            if (known.Vector3 is not null && SymbolEqualityComparer.Default.Equals(named, known.Vector3))
            {
                return new Shape(Kind.Vector3, Fq(named), isValueType: true);
            }

            if (known.Uri is not null && SymbolEqualityComparer.Default.Equals(named, known.Uri))
            {
                return new Shape(Kind.Uri, Fq(named), isValueType: false);
            }

            if (known.DateTimeOffset is not null && SymbolEqualityComparer.Default.Equals(named, known.DateTimeOffset))
            {
                return new Shape(Kind.DateTime, Fq(named), isValueType: true);
            }

            if (known.TimeSpan is not null && SymbolEqualityComparer.Default.Equals(named, known.TimeSpan))
            {
                return new Shape(Kind.Time, Fq(named), isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Boolean)
            {
                return new Shape(Kind.Bool, "bool", isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Int32)
            {
                return new Shape(Kind.Int32, "int", isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Int64)
            {
                return new Shape(Kind.Int64, "long", isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Double)
            {
                return new Shape(Kind.Double, "double", isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Single)
            {
                return new Shape(Kind.Single, "float", isValueType: true);
            }

            if (named.SpecialType == SpecialType.System_Decimal)
            {
                return new Shape(Kind.Decimal, "decimal", isValueType: true);
            }
        }

        throw new InvalidOperationException(
            "No polymorphic JSON conversion for '" + property.ContainingType.ToDisplayString() + "." + property.Name + "' of type '" + type.ToDisplayString() + "'."
        );
    }

    private static void EmitRegistry(StringBuilder output, HashSet<INamedTypeSymbol> generated)
    {
        output.AppendLine("namespace GuildWars2");
        output.AppendLine("{");
        output.AppendLine("    internal static class PolymorphicModelJson");
        output.AppendLine("    {");
        output.AppendLine("        public const string DiscriminatorName = \"$type\";");
        output.AppendLine();
        output.AppendLine("        public static bool CanConvert(Type typeToConvert)");
        output.AppendLine("        {");
        foreach (INamedTypeSymbol type in generated.OrderBy(static candidate => candidate.ToDisplayString(), StringComparer.Ordinal))
        {
            output.Append("            if (typeToConvert == typeof(").Append(Fq(type)).AppendLine("))");
            output.AppendLine("            {");
            output.AppendLine("                return true;");
            output.AppendLine("            }");
            output.AppendLine();
        }

        output.AppendLine("            return false;");
        output.AppendLine("        }");
        output.AppendLine();
        output.AppendLine("        public static JsonConverter? TryCreate(Type typeToConvert)");
        output.AppendLine("        {");
        foreach (INamedTypeSymbol type in generated.OrderBy(static candidate => candidate.ToDisplayString(), StringComparer.Ordinal))
        {
            output.Append("            if (typeToConvert == typeof(").Append(Fq(type)).AppendLine("))");
            output.AppendLine("            {");
            output.Append("                return new ").Append(Converter(type)).AppendLine("();");
            output.AppendLine("            }");
            output.AppendLine();
        }

        output.AppendLine("            return null;");
        output.AppendLine("        }");
        output.AppendLine("    }");
        output.AppendLine("}");
    }

    private static IEnumerable<IPropertySymbol> Properties(INamedTypeSymbol type)
    {
        List<INamedTypeSymbol> chain = [];
        for (INamedTypeSymbol? current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            chain.Add(current);
        }

        chain.Reverse();
        foreach (INamedTypeSymbol current in chain)
        {
            foreach (ISymbol member in current.GetMembers())
            {
                if (member is not IPropertySymbol property)
                {
                    continue;
                }

                if (!SymbolEqualityComparer.Default.Equals(property.ContainingType, current))
                {
                    continue;
                }

                if (property.DeclaredAccessibility != Accessibility.Public || property.IsStatic || property.IsIndexer || property.IsOverride)
                {
                    continue;
                }

                if (property.ExplicitInterfaceImplementations.Length > 0 || property.SetMethod is not { DeclaredAccessibility: Accessibility.Public or Accessibility.Internal })
                {
                    continue;
                }

                yield return property;
            }
        }
    }

    private static ITypeSymbol Unwrap(ITypeSymbol type, out bool nullable)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } named)
        {
            nullable = true;
            return named.TypeArguments[0];
        }

        nullable = type.NullableAnnotation == NullableAnnotation.Annotated;
        return type;
    }

    private static INamedTypeSymbol Root(INamedTypeSymbol type)
    {
        INamedTypeSymbol current = type;
        while (current.BaseType is { SpecialType: not SpecialType.System_Object } baseType && IsGuildWars(baseType))
        {
            current = baseType;
        }

        return current;
    }

    private static bool HasDescendants(INamedTypeSymbol type, List<INamedTypeSymbol> models)
    {
        foreach (INamedTypeSymbol candidate in models)
        {
            if (SymbolEqualityComparer.Default.Equals(candidate.BaseType, type))
            {
                return true;
            }
        }

        return false;
    }

    private static bool Inherits(INamedTypeSymbol type, INamedTypeSymbol ancestor)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, ancestor))
            {
                return true;
            }
        }

        return false;
    }

    private static int Depth(INamedTypeSymbol type)
    {
        int depth = 0;
        for (INamedTypeSymbol? current = type.BaseType; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            depth++;
        }

        return depth;
    }

    private static bool InDataFamily(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null && IsGuildWars(current); current = current.BaseType)
        {
            foreach (AttributeData attribute in current.GetAttributes())
            {
                if (attribute.AttributeClass?.Name is "DataTransferObjectAttribute" or "InheritableAttribute")
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static bool IsExcluded(INamedTypeSymbol type)
    {
        string name = type.ToDisplayString();
        return name is "GuildWars2.Flags" or "GuildWars2.Chat.Link" or "GuildWars2.Markup.MarkupNode";
    }

    private static bool IsGuildWars(INamedTypeSymbol type)
    {
        string? ns = type.ContainingNamespace?.ToDisplayString();
        return ns is not null && (ns == "GuildWars2" || ns.StartsWith("GuildWars2.", StringComparison.Ordinal));
    }

    private static string Fq(INamedTypeSymbol type)
    {
        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }

    private static string Converter(INamedTypeSymbol type)
    {
        return "global::" + type.ContainingNamespace.ToDisplayString() + "." + type.Name + "JsonConverter";
    }

    private static string Local(IPropertySymbol property)
    {
        string name = property.Name;
        return char.ToLowerInvariant(name[0]) + name.Substring(1) + "Json";
    }

    private static string Snake(string name)
    {
        StringBuilder builder = new();
        for (int i = 0; i < name.Length; i++)
        {
            char current = name[i];
            if (char.IsUpper(current)
                && i > 0
                && (char.IsLower(name[i - 1]) || (i + 1 < name.Length && char.IsLower(name[i + 1]))))
            {
                builder.Append('_');
            }

            builder.Append(char.ToLowerInvariant(current));
        }

        return builder.ToString();
    }

