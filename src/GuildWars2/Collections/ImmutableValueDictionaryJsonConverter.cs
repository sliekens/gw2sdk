using System.Diagnostics.CodeAnalysis;
using System.Text.Json;
using System.Text.Json.Serialization;
#if NET
using System.Text.Json.Serialization.Metadata;
#endif

namespace GuildWars2.Collections;

/// <summary>JSON converter factory for <see cref="ImmutableValueDictionary{TKey, TValue}"/>.</summary>
public sealed partial class ImmutableValueDictionaryJsonConverter : JsonConverterFactory
{
    /// <inheritdoc />
    public override bool CanConvert(Type typeToConvert)
    {
        ThrowHelper.ThrowIfNull(typeToConvert);
        if (!typeToConvert.IsGenericType)
        {
            return false;
        }

        Type genericTypeDefinition = typeToConvert.GetGenericTypeDefinition();
        return genericTypeDefinition == typeof(ImmutableValueDictionary<,>);
    }

    /// <inheritdoc />
    public override JsonConverter CreateConverter(
        Type typeToConvert,
        JsonSerializerOptions options
    )
    {
        ThrowHelper.ThrowIfNull(typeToConvert);
        Type[] typeArguments = typeToConvert.GetGenericArguments();
        return CreateKnownConverter(typeArguments[0], typeArguments[1]) ?? CreateConverterAtRuntime(typeToConvert, typeArguments);
    }

    /// <summary>Creates the converters that Native AOT must compile ahead of time. Generated by
    /// ImmutableValueCollectionConverterGenerator.</summary>
    /// <param name="keyType">The key type.</param>
    /// <param name="valueType">The value type.</param>
    /// <returns>The converter, or <c>null</c> when the type arguments are not known ahead of time.</returns>
    private static partial JsonConverter? CreateKnownConverter(Type keyType, Type valueType);

    [UnconditionalSuppressMessage(
        "AOT",
        "IL3050",
        Justification = "Only reached for element types that the generated CreateKnownConverter does not create statically"
            + " (the value types used by GW2SDK models, common primitives, and a reference-type template). Reference types"
            + " work under Native AOT through shared canonical code. Other value types need code that Native AOT cannot"
            + " generate at runtime; that case throws a NotSupportedException that explains the limitation."
            + " See https://github.com/sliekens/gw2sdk/issues/521."
    )]
    private static JsonConverter CreateConverterAtRuntime(Type typeToConvert, Type[] typeArguments)
    {
        try
        {
            return (JsonConverter)Activator.CreateInstance(typeof(Converter<,>).MakeGenericType(typeArguments))!;
        }
        catch (NotSupportedException exception)
        {
            throw ImmutableValueCollectionConverters.NotPrecompiled(typeToConvert, exception);
        }
    }

    private sealed class Converter<TKey, TValue> : JsonConverter<ImmutableValueDictionary<TKey, TValue>>
        where TKey : notnull
    {
#if NET
        private JsonTypeInfo<IImmutableDictionary<TKey, TValue>>? typeInfo;
#endif

        public override void Write(Utf8JsonWriter writer, ImmutableValueDictionary<TKey, TValue> value, JsonSerializerOptions options)
        {
#if NET
            JsonSerializer.Serialize(writer, value, ImmutableValueCollectionJson.GetDictionaryTypeInfo(ref typeInfo, options));
#else
            JsonSerializer.Serialize<IImmutableDictionary<TKey, TValue>>(writer, value, options);
#endif
        }

        public override ImmutableValueDictionary<TKey, TValue>? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        {
#if NET
            IImmutableDictionary<TKey, TValue>? dictionary = JsonSerializer.Deserialize(ref reader, ImmutableValueCollectionJson.GetDictionaryTypeInfo(ref typeInfo, options));
#else
            IImmutableDictionary<TKey, TValue>? dictionary = JsonSerializer.Deserialize<IImmutableDictionary<TKey, TValue>>(ref reader, options);
#endif
#pragma warning disable IDE0028 // Cannot simplify constructor calls that wrap ImmutableDictionary<TKey, TValue>.
            return dictionary is null ? null : new ImmutableValueDictionary<TKey, TValue>(dictionary);
#pragma warning restore IDE0028
        }
    }
}
